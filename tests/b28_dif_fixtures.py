"""Byte-identical reconstruction of the preserved 680-file corpus DIF inputs.

SHA-256 values were read from the original archive, not the new output.
These generated bytes must match the originals before a native test may run.
"""
from datetime import date, timedelta
import hashlib

SHA256 = (
    'd8ec658761c53b44c17563fc59a1bcdbce955a4e87a0696683aa61814ec1a5e2',
    '9f819b90d1a3fbe7eb58730e25453357df8496473dc1e951238ebe7f598b5fb4',
    '7f4e78208200640f4b5d3e24fa7d62a40c8f05a95882c88f9517a5ea9ecfa485',
    '82637dabe6c8020a0852f6a9b94fbc9ff8f8e408bcc16bb0c448a11e30eb3d5b',
    'b044364f5b96ffb9952f8e288921b43a7b03e21435802536dc7b1c4779f0fe4c',
    '0c60ef69885cdd6fa6e9b7d590210fb37729b9721923bece98f60c049e1b376c',
    'ca53da2a9d37c7d91cb013b4f3e4d1f6c11d4aae79db0f2678549fba00410a61',
    '3f0076bb1aded215f4352bd7b32a60d70e358ea1a52aaab99a2c135509dced83',
)


def original_dif(level):
    if type(level) is not int or not 1 <= level <= 8:
        raise ValueError('fixture_level')
    n = 6 + 9 * level
    lines = ['TABLE', '0,1', '"AIO_TEST"', 'VECTORS', '0,6', '""',
             'TUPLES', '0,' + str(n + 1), '""', 'DATA', '0,0', '""', '-1,0', 'BOT']
    for heading in ('ID', 'Label', 'Amount', 'Rate', 'Date', 'Memo'):
        lines += ['1,0', '"' + heading + '"']
    for i in range(1, n + 1):
        memo = (f'Batch {i}' if level < 4 else f"Комментарий {i}; рубрика, кавычка ' и ё")
        lines += ['-1,0', 'BOT', '1,0', f'"{i:03d}"', '1,0', f'"Строка {i} / QA L{level}"',
                  f'0,{i * 1.43:.2f}', 'V', f'0,{(i % 11 - 5) / 100:.3f}', 'V',
                  '1,0', '"' + str(date(2026, 10, 26) + timedelta(days=i)) + '"',
                  '1,0', '"' + memo + '"']
    data = ('\r\n'.join(lines + ['-1,0', 'EOD']) + '\r\n').encode('utf-8')
    if hashlib.sha256(data).hexdigest() != SHA256[level - 1]:
        raise AssertionError('fixture bytes differ from preserved original L' + str(level))
    return data
